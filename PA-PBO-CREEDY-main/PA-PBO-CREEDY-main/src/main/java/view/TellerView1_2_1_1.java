    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
 String noRek = jTextField2.getText().trim();
    String nominalStr = jTextField3.getText().trim();

    if (noRek.isEmpty() || nominalStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Pilih rekening dari tabel dan masukkan nominal setoran!");
        return;
    }

    double jumlahSetor = 0;
    try {
        jumlahSetor = Double.parseDouble(nominalStr);
        if (jumlahSetor <= 0) {
            JOptionPane.showMessageDialog(this, "Nominal setoran harus lebih besar dari 0!");
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Nominal setoran harus berupa angka yang valid!");
        return;
    }

    Connection conn = null;
    try {
        conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/pa_creedy", "root", "");
        conn.setAutoCommit(false);

        // 1. Cek status dan saldo rekening saat ini
        String sqlCek = "SELECT saldo, status_rekening FROM rekening WHERE nomor_rekening = ?";
        PreparedStatement pstCek = conn.prepareStatement(sqlCek);
        pstCek.setString(1, noRek);
        ResultSet rsCek = pstCek.executeQuery();

        if (!rsCek.next()) {
            JOptionPane.showMessageDialog(this, "Nomor rekening tidak ditemukan!");
            return;
        }

        double saldoAktif = rsCek.getDouble("saldo");
        String status = rsCek.getString("status_rekening");

        if (!"Aktif".equalsIgnoreCase(status)) {
            JOptionPane.showMessageDialog(this, "Rekening ini sudah tidak aktif / ditutup!");
            return;
        }

        double saldoBaru = saldoAktif + jumlahSetor; // <--- SALDO BERTAMBAH

        // 2. Update saldo baru ke database
        String sqlUpdate = "UPDATE rekening SET saldo = ? WHERE nomor_rekening = ?";
        PreparedStatement pstUpdate = conn.prepareStatement(sqlUpdate);
        pstUpdate.setDouble(1, saldoBaru);
        pstUpdate.setString(2, noRek);
        pstUpdate.executeUpdate();

        // 3. Generate ID Transaksi otomatis
        Statement stmtTrx = conn.createStatement();
        ResultSet rsTrx = stmtTrx.executeQuery("SELECT MAX(CAST(SUBSTRING(transaksi_id, 4) AS UNSIGNED)) AS max_trx FROM transaksi");
        int nextTrxId = 1;
        if (rsTrx.next()) {
            nextTrxId = rsTrx.getInt("max_trx") + 1;
        }
        String newTrxId = String.format("TRX%04d", nextTrxId);

        // 4. Ambil ID Teller dari Session
        String tellerUserId = "USR002";
        try {
            String sessionUser = model.UserSession.getUserId();
            if (sessionUser != null && !sessionUser.isEmpty()) {
                tellerUserId = sessionUser;
            }
        } catch (Exception ex) {}

        // 5. Catat riwayat ke tabel transaksi dengan jenis 'Setor Tunai'
        String sqlInsTrx = "INSERT INTO transaksi (transaksi_id, jenis_transaksi, jumlah, saldo_setelah, channel, waktu_transaksi, keterangan, nomor_rekening, pegawai_user_id) " +
                           "VALUES (?, 'Setor Tunai', ?, ?, 'Teller', NOW(), 'Setoran tunai oleh teller', ?, ?)";
        PreparedStatement pstInsTrx = conn.prepareStatement(sqlInsTrx);
        pstInsTrx.setString(1, newTrxId);
        pstInsTrx.setDouble(2, jumlahSetor);
        pstInsTrx.setDouble(3, saldoBaru);
        pstInsTrx.setString(4, noRek);
        pstInsTrx.setString(5, tellerUserId);
        pstInsTrx.executeUpdate();

        conn.commit();
        JOptionPane.showMessageDialog(this, "Setor Tunai Berhasil!\nJumlah Setor: Rp " + jumlahSetor + "\nSaldo Terbaru: Rp " + saldoBaru);

        tampilDataRekening(); 
        jButton4ActionPerformed(null); // Bersihkan form

    } catch (Exception e) {
        try { if (conn != null) conn.rollback(); } catch (Exception ex) {}
        JOptionPane.showMessageDialog(this, "Gagal melakukan setor tunai: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton3ActionPerformed

