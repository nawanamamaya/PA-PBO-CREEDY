private void tampilDataRekening() {
    DefaultTableModel model = new DefaultTableModel() {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false; // Kunci tabel agar Read-Only
        }
    };
    
    model.addColumn("Nomor Rekening");
    model.addColumn("NIK");
    model.addColumn("Nama Nasabah");
    model.addColumn("Saldo");
    model.addColumn("Status");
    jTable1.setModel(model); 

    try {
        Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/pa_creedy", "root", "");
        Statement stmt = conn.createStatement();
        
        String sql = "SELECT r.nomor_rekening, n.nik, u.nama_lengkap, r.saldo, r.status_rekening " +
                     "FROM rekening r " +
                     "JOIN nasabah n ON r.nasabah_user_id = n.user_id " +
                     "JOIN users u ON n.user_id = u.user_id " +
                     "WHERE r.status_rekening = 'Aktif'";
        ResultSet rs = stmt.executeQuery(sql);

while (rs.next()) {
    model.addRow(new Object[]{
        rs.getString("nomor_rekening"),
        rs.getString("nik"),
        rs.getString("nama_lengkap"),
        rs.getString("saldo"), // <--- Ubah dari getDouble ke getString
        rs.getString("status_rekening")
    });
}
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal memuat daftar rekening: " + e.getMessage());
    }
}

