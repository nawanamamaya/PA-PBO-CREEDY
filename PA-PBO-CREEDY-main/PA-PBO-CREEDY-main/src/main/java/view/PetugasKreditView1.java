    private javax.swing.JButton tombolSatuanTenor;
    private List<PegawaiDAO.NasabahPilihan> daftar=List.of();
    private void siapkan() {
        jLabel8.setText("Data Nasabah Pemohon");
        jTextArea2.setText("Pilih nasabah dan rekening aktif miliknya. Isi nominal, jangka waktu, dan tujuan lalu kirim pengajuan.");
        tombolSatuanTenor=config.jangkaWaktu(jTextField2,jPanel2);jLabel11.setText("Jangka Waktu");
        jTextField1.setText("");jTextField2.setText("");
        jComboBox1.removeAllItems();jComboBox2.removeAllItems();
        jComboBox1.addActionListener(e -> muatRekening());
        config.run(this, () -> new PegawaiDAO().nasabah(userId,""), rows -> {
            daftar=rows;config.combo(jComboBox1,rows.stream().map(Object::toString).toList());
            muatRekening();
        });
    }
    private void muatRekening() {
        int index=jComboBox1.getSelectedIndex();
        config.combo(jComboBox2,List.of());
        if(index<0 || index>=daftar.size())return;
        String nasabahId=daftar.get(index).userId();
        config.run(this, () -> new PegawaiDAO().rekeningNasabah(userId,nasabahId), rows -> config.combo(jComboBox2,rows));
    }
    private void bersihkan() {jTextField1.setText("");config.resetTenor(jTextField2,tombolSatuanTenor);jTextArea1.setText("");}
    private void kirim() {
        int index=jComboBox1.getSelectedIndex();
        if(index<0 || index>=daftar.size())throw new IllegalArgumentException("Pilih nasabah pemohon.");
        String nasabah=daftar.get(index).userId(),rekening=config.selected(jComboBox2),jumlah=jTextField1.getText().trim(),tenor=jTextField2.getText().trim(),unit=(String)tombolSatuanTenor.getClientProperty("satuan"),tujuan=jTextArea1.getText().trim();
        config.run(this, () -> new com.mycompany.caps_creedy.dao.PinjamanDAO().ajukanPetugas(userId,nasabah,rekening,jumlah,config.tenorBulan(tenor,unit),tujuan), id -> {bersihkan();config.info(this,"Pengajuan "+id+" berhasil disimpan dengan status Diajukan.");});
    }

