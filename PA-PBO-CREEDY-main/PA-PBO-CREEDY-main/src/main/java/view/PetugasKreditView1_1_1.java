    private final String userId=UserSession.getUserId();

    private List<PegawaiDAO.NasabahPilihan> daftar=List.of();
    private void siapkan() {
        jTable1.setModel(config.table(new String[]{"Data"},List.of()));
        jLabel7.setText("Cari Nasabah (NIK / Nama)");jLabel8.setText("Nasabah Aktif");
        jTextArea1.setEditable(false);jTextArea1.setLineWrap(true);jTextArea1.setWrapStyleWord(true);
        jTextArea2.setText("Klik baris nasabah untuk melihat detail dan nomor rekening aktifnya. Total tagihan mencakup pokok, bunga, dan denda yang belum lunas.");
        jButton1.addActionListener(e -> muatNasabah());
        jTable1.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        jTable1.getSelectionModel().addListSelectionListener(e -> {
            if(!e.getValueIsAdjusting() && !Boolean.TRUE.equals(getRootPane().getClientProperty("busy"))) muatDetail();
        });
        muatNasabah();
    }
    private void muatNasabah() {
        String cari=jTextField4.getText().trim();jTextArea1.setText("");
        config.run(this, () -> new PegawaiDAO().nasabah(userId,cari), rows -> {
            daftar=rows;jTable1.setModel(config.table(new String[]{"NIK","Nama Lengkap","Alamat","Total Tagihan Belum Lunas"},rows.stream().map(r -> new Object[]{r.nik(),r.nama(),r.alamat(),r.tagihan()}).toList()));
            if(rows.isEmpty())jTextArea1.setText("Nasabah tidak ditemukan.");
        });
    }
    private void muatDetail() {
        int row=jTable1.getSelectedRow();if(row<0)return;
        String id=daftar.get(jTable1.convertRowIndexToModel(row)).userId();
        config.run(this, () -> new PegawaiDAO().detailNasabah(userId,id), detail -> jTextArea1.setText(detail));
    }

