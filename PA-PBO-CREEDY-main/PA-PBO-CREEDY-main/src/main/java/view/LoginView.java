    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String identifier=jTextField2.getText().trim(), password=new String(jTextField1.getPassword()), role=selectedRole;
        config.run(this, () -> new com.mycompany.caps_creedy.proses.Autentikasi().login(identifier,password,role), akun -> {
            jTextField1.setText("");
            if(akun==null){config.info(this,"Login gagal. Periksa identitas, password, peran, dan status akun.");return;}
            com.mycompany.caps_creedy.proses.UserSession.setSession(akun.getUserId(),akun.getEmail(),akun.getNama(),akun.getRole());
            switch(akun.getRole()) {
                case "Nasabah" -> config.open(this,NasabahView1::new);
                case "Admin" -> config.open(this,AdminView2::new);
                case "Teller" -> config.open(this,TellerView::new);
                case "Petugas Kredit" -> config.open(this,PetugasKreditView1::new);
                default -> throw new IllegalStateException("Peran akun tidak dikenali.");
            }
        });
    }//GEN-LAST:event_jButton1ActionPerformed

