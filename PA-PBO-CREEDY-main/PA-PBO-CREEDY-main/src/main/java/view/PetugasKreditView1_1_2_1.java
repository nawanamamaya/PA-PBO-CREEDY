    private String pencarian="";
    private void siapkan() {
        jTable1.setModel(config.table(new String[]{"Data"},List.of()));
        jLabel1.setText("Tunggakan & Denda");jLabel8.setText("Pemantauan Pinjaman Aktif");
        jTextArea2.setText("Tunggakan dihitung dari jadwal lewat jatuh tempo yang belum lunas pada pinjaman aktif. Total tunggakan berisi pokok + bunga; total denda ditampilkan terpisah sesuai nilai tercatat, tanpa menambahkan denda baru.");
        jTextField1.setEditable(false);jTextField2.setEditable(false);jTextField3.setEditable(false);
        config.combo(jComboBox1,List.of("Semua keterlambatan","Minimal 7 hari","Minimal 30 hari","Minimal 90 hari"));
        config.posisiCari(this,jButton1,jButton2);
        jButton4.addActionListener(e -> muatTunggakan());
        jComboBox1.addActionListener(e -> muatTunggakan());
        muatTunggakan();
    }
    private void muatTunggakan() {
        int[] batas={1,7,30,90};int index=jComboBox1.getSelectedIndex();if(index<0)return;
        int hari=batas[index];String cari=pencarian;
        config.run(this, () -> new PegawaiDAO().tunggakan(userId,hari,cari), data -> {
            jTable1.setModel(config.table(new String[]{"Nasabah","ID Pinjaman","Jatuh Tempo","Terlambat (hari)","Pokok + Bunga","Denda Tercatat"},data.rows()));
            jTextField1.setText(String.valueOf(data.rows().size()));jTextField2.setText(data.tagihan().toPlainString());jTextField3.setText(data.denda().toPlainString());
        });
    }
    private void cari() {
        String hasil=javax.swing.JOptionPane.showInputDialog(this,"Cari ID pinjaman, NIK, atau nama. Kosongkan untuk menampilkan semua tunggakan sesuai filter.",pencarian);
        if(hasil!=null){pencarian=hasil;muatTunggakan();}
    }

