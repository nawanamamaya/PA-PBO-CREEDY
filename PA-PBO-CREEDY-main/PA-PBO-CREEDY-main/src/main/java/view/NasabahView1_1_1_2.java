    private final String userId = UserSession.getUserId();

    private TransaksiDAO.Tagihan tagihan;
    private void muatData() {
        tagihan=null;jButton3.setEnabled(false);jTextArea1.setEditable(false);
        jTextArea2.setText("Pembayaran melunasi satu angsuran paling awal yang belum lunas. Denda mengikuti nilai yang tercatat di database.");
        jComboBox1.removeAllItems();jComboBox2.removeAllItems();
        jComboBox1.addActionListener(e -> muatTagihan());
        config.run(this, () -> {
            List<String> ids=new PinjamanDAO().daftar(userId).stream().filter(r -> "Aktif".equals(r[4])).map(r -> (String)r[0]).toList();
            return List.of(ids,new NasabahDAO().nomorRekening(userId));
        }, lists -> {
            config.combo(jComboBox2,lists.get(1));config.combo(jComboBox1,lists.get(0));
            if(lists.get(0).isEmpty())jTextArea1.setText("Belum ada pinjaman aktif.");
            else muatTagihan();
        });
    }
    private void muatTagihan() {
        tagihan=null;jButton3.setEnabled(false);jTextArea1.setText("");
        if(jComboBox1.getSelectedItem()==null)return;
        String id=config.selected(jComboBox1);
        config.run(this, () -> new TransaksiDAO().tagihan(userId,id), data -> {
            tagihan=data;jTextArea1.setText(data.rincian());jButton3.setEnabled(jComboBox2.getItemCount()>0);
        });
    }
    private void bayar() {
        if(tagihan==null)throw new IllegalArgumentException("Pilih pinjaman dengan tagihan yang belum lunas.");
        String id=config.selected(jComboBox1),rekening=config.selected(jComboBox2);
        TransaksiDAO.Tagihan snapshot=tagihan;
        if(javax.swing.JOptionPane.showConfirmDialog(this,snapshot.rincian()+"\nDari rekening: "+rekening+"\nLanjutkan pembayaran?","Konfirmasi pembayaran",javax.swing.JOptionPane.YES_NO_OPTION)!=javax.swing.JOptionPane.YES_OPTION)return;
        config.run(this, () -> {new TransaksiDAO().bayar(userId,id,rekening,snapshot.id(),snapshot.jumlah());return true;}, ok -> {
            tagihan=null;jButton3.setEnabled(false);jTextArea1.setText("Pembayaran berhasil. Pilih kembali pinjaman untuk memuat tagihan berikutnya.");
            config.info(this,"Angsuran "+snapshot.id()+" berhasil dibayar.");
        });
    }

