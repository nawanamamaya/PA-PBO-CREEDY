    private void muatData() {
        jTextField8.setText("12% per tahun (flat)");jTextField8.setEditable(false);
        config.run(this, () -> new NasabahDAO().nomorRekening(userId), list -> {
            jTextField3.setText(list.isEmpty()?"":list.getFirst());
            jTextField3.setToolTipText("Isi nomor rekening aktif milik Anda: "+String.join(", ",list));
        });
    }
    private void bersihkan() {jTextField2.setText("");config.resetTenor(jTextField7,tombolSatuanTenor);jTextArea1.setText("");}
    private void kirim() {
        String rekening=jTextField3.getText().trim(),jumlah=jTextField2.getText().trim(),tenor=jTextField7.getText().trim(),satuan=(String)tombolSatuanTenor.getClientProperty("satuan"),tujuan=jTextArea1.getText().trim();
        config.run(this, () -> new PinjamanDAO().ajukan(userId,rekening,jumlah,config.tenorBulan(tenor,satuan),tujuan), id -> {
            bersihkan();config.info(this,"Pengajuan "+id+" berhasil disimpan dengan status Diajukan.");
        });
    }

