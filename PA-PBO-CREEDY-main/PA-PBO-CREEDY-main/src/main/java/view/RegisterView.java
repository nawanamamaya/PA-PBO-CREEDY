    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    String nama = jTextField4.getText().trim();
        String nik = jTextField5.getText().trim();
        String noHp = jTextField2.getText().trim();
        String tipeNasabah = jComboBox1.getSelectedItem().toString();
        String npwp = jTextField3.getText().trim();
        String email = jTextField6.getText().trim();
        String alamat = jTextArea1.getText().trim();
        String password = jTextField1.getText().trim();

        // Check value jika masih teks placeholder
        if (nama.equals("Nama sessuai KTP")) nama = "";
        if (nik.equals("16 digit NIK")) nik = "";
        if (noHp.equals("Contoh: 085705704516")) noHp = "";
        if (npwp.equals("Jika ada")) npwp = null;
        if (alamat.equals("Alamat lengkap")) alamat = "";

        // Validasi Field Wajib
        if (nama.isEmpty() || nik.isEmpty() || noHp.isEmpty() || email.isEmpty() || password.isEmpty() || alamat.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mohon lengkapi seluruh data wajib!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (nik.length() != 16) {
            JOptionPane.showMessageDialog(this, "NIK harus terdiri dari 16 digit!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Connection conn = null;
        try {
            conn = config.configDB();
            conn.setAutoCommit(false); // Transaksi ganda (users & nasabah)

            // 1. Generate User ID (USR + timestamp 5 digit)
            String userId = "USR" + (System.currentTimeMillis() % 100000);

            // 2. Insert ke tabel 'users'
            String sqlUser = "INSERT INTO users (user_id, email, password, nama_lengkap, status, user_type) VALUES (?, ?, ?, ?, 'Aktif', 'Nasabah')";
            PreparedStatement pstUser = conn.prepareStatement(sqlUser);
            pstUser.setString(1, userId);
            pstUser.setString(2, email);
            pstUser.setString(3, password);
            pstUser.setString(4, nama);
            pstUser.executeUpdate();

            // 3. Insert ke tabel 'nasabah'
            String sqlNasabah = "INSERT INTO nasabah (nik, user_id, npwp, tipe_nasabah, alamat, no_telepon, tanggal_daftar) VALUES (?, ?, ?, ?, ?, ?, ?)";
            PreparedStatement pstNasabah = conn.prepareStatement(sqlNasabah);
            pstNasabah.setString(1, nik);
            pstNasabah.setString(2, userId);
            pstNasabah.setString(3, npwp);
            pstNasabah.setString(4, tipeNasabah);
            pstNasabah.setString(5, alamat);
            pstNasabah.setString(6, noHp);
            
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            pstNasabah.setString(7, sdf.format(new Date()));
            
            pstNasabah.executeUpdate();

            conn.commit(); // Simpan kedua transaksi ke database MySQL
            
            JOptionPane.showMessageDialog(this, "Pendaftaran Akun Nasabah Berhasil! Silakan Login.", "Sukses", JOptionPane.INFORMATION_MESSAGE);
            
            // Pindah ke LoginView
            new LoginView().setVisible(true);
            this.dispose();

        } catch (Exception e) {
            if (conn != null) {
                try {
                    conn.rollback(); // Batalkan jika salah satu tabel gagal insert
                } catch (SQLException ex) {
                    logger.log(java.util.logging.Level.SEVERE, null, ex);
                }
            }
            JOptionPane.showMessageDialog(this, "Gagal Mendaftar: " + e.getMessage(), "Error Database", JOptionPane.ERROR_MESSAGE);
        }
        finally {
            if(conn!=null)try{conn.close();}catch(SQLException ex){logger.log(java.util.logging.Level.WARNING,"Gagal menutup koneksi registrasi",ex);}
        }
    }//GEN-LAST:event_jButton1ActionPerformed

