    private final String userId = UserSession.getUserId();

    private void muatData() {
        config.run(this, () -> new NasabahDAO().ringkasan(userId), data -> {
            jTable1.setModel(config.table(new String[]{"Nomor", "Jenis Rekening", "Saldo", "Status"},
                data.rekening().stream().map(r -> new Object[]{r.nomor(),r.jenis(),r.saldo(),r.status()}).toList()));
            jTextField2.setText(data.rekening().stream().map(NasabahDAO.Rekening::saldo).reduce(BigDecimal.ZERO,BigDecimal::add).toPlainString());
            jTextField3.setText(String.valueOf(data.rekening().size()));
            jTextField7.setText(String.valueOf(data.pinjamanAktif()));
        });
    }

