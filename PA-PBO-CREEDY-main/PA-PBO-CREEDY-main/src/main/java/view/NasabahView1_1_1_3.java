    private final String userId = UserSession.getUserId();

    private void muatData() {
        jTextField1.setEditable(false);jTextField2.setEditable(false);jTextField3.setEditable(false);
        jComboBox1.removeAllItems();jComboBox1.addActionListener(e -> muatJadwal());
        config.run(this, () -> new PinjamanDAO().pilihan(userId), ids -> {
            config.combo(jComboBox1,ids);
            if(ids.isEmpty()) tampilJadwal(new PinjamanDAO.Jadwal(List.of(),BigDecimal.ZERO,BigDecimal.ZERO,BigDecimal.ZERO));
            else muatJadwal();
        });
    }
    private void muatJadwal() {
        if(jComboBox1.getSelectedItem()==null)return;
        String id=config.selected(jComboBox1);
        config.run(this, () -> new PinjamanDAO().jadwal(userId,id), this::tampilJadwal);
    }
    private void tampilJadwal(PinjamanDAO.Jadwal data) {
        jTable1.setModel(config.table(new String[]{"ID Angsuran","Jatuh Tempo","Pokok + Bunga","Denda Tercatat","Status"},data.rows()));
        jTextField1.setText(data.angsuran().toPlainString());jTextField2.setText(data.sisa().toPlainString());jTextField3.setText(data.denda().toPlainString());
    }

