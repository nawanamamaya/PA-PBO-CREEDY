private void tampilDataCabang() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID Cabang");
    model.addColumn("Wilayah Cabang");
    model.addColumn("Alamat");
    model.addColumn("Nomor Telepon");

    try {
        Connection conn = config.configDB(); 
        Statement stmt = conn.createStatement();
        String sql = "SELECT cabang_id, nama_cabang, alamat, no_telepon FROM cabang ORDER BY cabang_id ASC";
        ResultSet res = stmt.executeQuery(sql);

        while (res.next()) {
            model.addRow(new Object[]{
                res.getString("cabang_id"),
                res.getString("nama_cabang"),
                res.getString("alamat"),     // [DIBETULKAN] Ditambahkan koma di akhir
                res.getString("no_telepon")  // [DIBETULKAN] Hapus koma setelahnya
            });
        }

        jTable1.setModel(model);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, 
            "Gagal mengambil data cabang: " + e.getMessage(), 
            "Error Database", 
            JOptionPane.ERROR_MESSAGE);
    }
}
    
