    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    String namaCabang = jTextField5.getText().trim(); // Sesuaikan nama textfield Nama Cabang
    String alamat = jTextField3.getText().trim();     // Sesuaikan nama textfield Alamat
    String noTelepon = jTextField2.getText().trim();  // Sesuaikan nama textfield No Telepon

    if (namaCabang.isEmpty() || alamat.isEmpty() || noTelepon.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Semua field harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        Connection conn = config.configDB();
        
        // Generate ID Cabang otomatis (CBG016, CBG017, dst)
        String nextCabangId = generateNextCabangId(conn);

        String sql = "INSERT INTO cabang (cabang_id, nama_cabang, alamat, no_telepon) VALUES (?, ?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, nextCabangId);
        pst.setString(2, namaCabang);
        pst.setString(3, alamat);
        pst.setString(4, noTelepon);

        pst.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data cabang berhasil ditambahkan dengan ID: " + nextCabangId);

        tampilDataCabang(); // Refresh tabel
        // bersihkanForm(); // Panggil fungsi bersih form jika ada
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Gagal menambah cabang: " + e.getMessage(), "Error Database", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
    int row = jTable1.getSelectedRow();
        String kodeCabang = jTextField2.getText().trim();

        if (row == -1 && kodeCabang.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih data cabang pada tabel yang ingin diubah!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (kodeCabang.isEmpty()) {
            kodeCabang = jTable1.getValueAt(row, 0).toString();
        }

        String namaCabang = jTextField5.getText().trim();
        String alamat = jTextField3.getText().trim();

        if (namaCabang.isEmpty() || alamat.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama Cabang dan Alamat tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Connection conn = config.configDB();
            String sql = "UPDATE cabang SET nama_cabang=?, alamat=? WHERE cabang_id=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, namaCabang);
            pst.setString(2, alamat);
            pst.setString(3, kodeCabang);
            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Data kantor cabang berhasil diperbarui!");
            tampilDataCabang();
            bersihkanForm();

        } catch (HeadlessException | SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memperbarui data cabang: " + e.getMessage(), "Error Database", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

