private void tampilDataNasabah() {
    // Kunci seluruh sel tabel agar tidak bisa diedit langsung saat diklik 2x
    DefaultTableModel model = new DefaultTableModel() {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false; // Mengembalikan false agar tabel read-only
        }
    };
    
    model.addColumn("ID Nasabah");
    model.addColumn("Nama Lengkap");
    model.addColumn("Email");
    model.addColumn("Nomor Telepon");
    model.addColumn("Alamat");
    jTable1.setModel(model); 

    try {
        Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/pa_creedy", "root", "");
        Statement stmt = conn.createStatement();
        
        String sql = "SELECT u.user_id, u.nama_lengkap, u.email, n.no_telepon, n.alamat " +
                     "FROM users u INNER JOIN nasabah n ON u.user_id = n.user_id " +
                     "WHERE u.user_type = 'Nasabah'";
        ResultSet rs = stmt.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("user_id"),
                rs.getString("nama_lengkap"),
                rs.getString("email"),
                rs.getString("no_telepon"),
                rs.getString("alamat")
            });
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
    }
}
