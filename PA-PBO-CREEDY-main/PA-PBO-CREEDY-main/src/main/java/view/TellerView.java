    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
 int baris = jTable1.getSelectedRow();
    if (baris != -1) {
        // Ambil data dari tabel berdasarkan urutan kolom
        String idNasabah = jTable1.getValueAt(baris, 0).toString(); // Ini user_id
        
        jTextField3.setText(jTable1.getValueAt(baris, 1).toString()); // Nama Lengkap
        jTextField7.setText(jTable1.getValueAt(baris, 2).toString()); // Email
        jTextField6.setText(jTable1.getValueAt(baris, 3).toString()); // Nomor Telepon
        jTextArea1.setText(jTable1.getValueAt(baris, 4).toString());  // Alamat
        
        // Karena NIK dan Password tidak ditampilkan di tabel, kita query langsung dari database
        try {
            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/pa_creedy", "root", "");
            String sql = "SELECT n.nik, u.password FROM nasabah n JOIN users u ON n.user_id = u.user_id WHERE n.user_id = ?";
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, idNasabah);
            java.sql.ResultSet rs = pst.executeQuery();
            
            if (rs.next()) {
                jTextField2.setText(rs.getString("nik"));
                jTextField8.setText(rs.getString("password"));
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat NIK/Password: " + e.getMessage());
        }

        // Kunci kolom NIK agar tidak bisa diedit (sebagai patokan primary key saat update data)
        jTextField2.setEditable(false);
    }
    }//GEN-LAST:event_jTable1MouseClicked

