    private final String userId = UserSession.getUserId();

    private List<NasabahDAO.Rekening> rekening=List.of();
    private void muatData() {
        jButton3.setText("Kirim Transfer");jTextArea1.setEditable(false);
        jTextArea2.setText("Transfer hanya ke rekening aktif. Periksa nomor tujuan dan nominal sebelum mengonfirmasi.");
        jComboBox1.removeAllItems();jComboBox1.addActionListener(e -> tampilRekening());
        config.run(this, () -> new NasabahDAO().rekening(userId,true), data -> {
            rekening=data;config.combo(jComboBox1,data.stream().map(NasabahDAO.Rekening::nomor).toList());tampilRekening();
        });
    }
    private void tampilRekening() {
        String nomor=Objects.toString(jComboBox1.getSelectedItem(),"");
        jTextArea1.setText(rekening.stream().filter(r -> r.nomor().equals(nomor)).findFirst()
            .map(r -> "Nomor: "+r.nomor()+"\nJenis: "+r.jenis()+"\nSaldo: Rp "+r.saldo()).orElse("Belum ada rekening aktif."));
    }
    private void bersihkan() {jTextField1.setText("");jTextField2.setText("");jTextField3.setText("");}
    private void transfer() {
        String sumber=config.selected(jComboBox1),tujuan=jTextField1.getText().trim(),nominal=jTextField2.getText().trim(),catatan=jTextField3.getText().trim();
        BigDecimal jumlah=TransaksiDAO.nominal(nominal);
        if(tujuan.isEmpty() || tujuan.equals(sumber))throw new IllegalArgumentException("Isi rekening tujuan yang berbeda dari rekening sumber.");
        if(javax.swing.JOptionPane.showConfirmDialog(this,"Transfer Rp "+jumlah+"\nDari: "+sumber+"\nKe: "+tujuan+"\nLanjutkan?","Konfirmasi transfer",javax.swing.JOptionPane.YES_NO_OPTION)!=javax.swing.JOptionPane.YES_OPTION)return;
        config.run(this, () -> {new TransaksiDAO().transfer(userId,sumber,tujuan,nominal,catatan);return true;}, ok -> {
            bersihkan();config.info(this,"Transfer berhasil.");
            config.run(this, () -> new NasabahDAO().rekening(userId,true), data -> {rekening=data;tampilRekening();});
        });
    }

