private void tampilDataPinjaman() {
    DefaultTableModel model = new DefaultTableModel() {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false; // Kunci tabel Read-Only
        }
    };
    
    model.addColumn("Nomor Pinjaman");
    model.addColumn("Nama Nasabah");
    model.addColumn("Jumlah Pinjaman");
    model.addColumn("Status");
    jTable1.setModel(model); 

    try {
        Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/pa_creedy", "root", "");
        Statement stmt = conn.createStatement();
        
        // Menggunakan pinjaman_id dan status sesuai struktur database pa_creedy.sql[cite: 8]
        String sql = "SELECT p.pinjaman_id, u.nama_lengkap, p.jumlah_pinjaman, p.status " +
                     "FROM pinjaman p " +
                     "JOIN nasabah n ON p.nasabah_user_id = n.user_id " +
                     "JOIN users u ON n.user_id = u.user_id " +
                     "WHERE p.status = 'Aktif'";
        ResultSet rs = stmt.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("pinjaman_id"),
                rs.getString("nama_lengkap"),
                rs.getString("jumlah_pinjaman"),
                rs.getString("status")
            });
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal memuat daftar pinjaman: " + e.getMessage());
    }
    this.setLocationRelativeTo(null);
}

