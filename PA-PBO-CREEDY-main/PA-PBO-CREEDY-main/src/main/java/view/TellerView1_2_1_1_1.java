    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
String noPinjaman = jTextField2.getText().trim();
    String nominalStr = jTextField3.getText().trim();

    if (noPinjaman.isEmpty() || nominalStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Pilih pinjaman dari tabel dan masukkan nominal angsuran!");
        return;
    }

    double jumlahBayar = 0;
    try {
        jumlahBayar = Double.parseDouble(nominalStr);
        if (jumlahBayar <= 0) {
            JOptionPane.showMessageDialog(this, "Nominal angsuran harus lebih besar dari 0!");
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Nominal angsuran harus berupa angka yang valid!");
        return;
    }

    Connection conn = null;
    try {
        conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/pa_creedy", "root", "");
        conn.setAutoCommit(false); // Transaksi ganda

        // 1. Cek data pinjaman saat ini di database pa_creedy.sql
        String sqlCek = "SELECT pinjaman_id, jumlah_pinjaman, status, nasabah_user_id FROM pinjaman WHERE pinjaman_id = ?";
        PreparedStatement pstCek = conn.prepareStatement(sqlCek);
        pstCek.setString(1, noPinjaman);
        ResultSet rsCek = pstCek.executeQuery();

        if (!rsCek.next()) {
            JOptionPane.showMessageDialog(this, "Nomor pinjaman tidak ditemukan!");
            return;
        }

        double jumlahPinjamanAktif = rsCek.getDouble("jumlah_pinjaman");
        String status = rsCek.getString("status");
        String nasabahUserId = rsCek.getString("nasabah_user_id");

        if (!"Aktif".equalsIgnoreCase(status)) {
            JOptionPane.showMessageDialog(this, "Pinjaman ini sudah lunas atau tidak aktif!");
            return;
        }

        if (jumlahBayar > jumlahPinjamanAktif) {
            JOptionPane.showMessageDialog(this, "Nominal pembayaran melebihi sisa pinjaman!\nJumlah Pinjaman: Rp " + String.format("%.0f", jumlahPinjamanAktif));
            return;
        }

        // 2. Hitung sisa pinjaman baru dan tentukan statusnya
        double sisaPinjamanBaru = jumlahPinjamanAktif - jumlahBayar;
        String statusBaru = (sisaPinjamanBaru <= 0) ? "Lunas" : "Aktif";

        // 3. UPDATE jumlah pinjaman dan status di tabel pinjaman database pa_creedy.sql
        String sqlUpdatePinjaman = "UPDATE pinjaman SET jumlah_pinjaman = ?, status = ? WHERE pinjaman_id = ?";
        PreparedStatement pstUpdate = conn.prepareStatement(sqlUpdatePinjaman);
        pstUpdate.setDouble(1, sisaPinjamanBaru);
        pstUpdate.setString(2, statusBaru);
        pstUpdate.setString(3, noPinjaman);
        pstUpdate.executeUpdate();

        // 4. Ambil nomor rekening aktif milik nasabah untuk syarat pencatatan transaksi
        String nomorRekening = "";
        double saldoRekening = 0;
        String sqlRek = "SELECT nomor_rekening, saldo FROM rekening WHERE nasabah_user_id = ? AND status_rekening = 'Aktif' LIMIT 1";
        PreparedStatement pstRek = conn.prepareStatement(sqlRek);
        pstRek.setString(1, nasabahUserId);
        ResultSet rsRek = pstRek.executeQuery();
        
        if (rsRek.next()) {
            nomorRekening = rsRek.getString("nomor_rekening");
            saldoRekening = rsRek.getDouble("saldo");
        } else {
            JOptionPane.showMessageDialog(this, "Rekening aktif untuk nasabah ini tidak ditemukan!");
            return;
        }

        // 5. Generate ID Transaksi otomatis
        Statement stmtTrx = conn.createStatement();
        ResultSet rsTrx = stmtTrx.executeQuery("SELECT MAX(CAST(SUBSTRING(transaksi_id, 4) AS UNSIGNED)) AS max_trx FROM transaksi");
        int nextTrxId = 1;
        if (rsTrx.next()) {
            nextTrxId = rsTrx.getInt("max_trx") + 1;
        }
        String newTrxId = String.format("TRX%04d", nextTrxId);

        // 6. Ambil ID Teller dari Session
        String tellerUserId = "USR002";
        try {
            String sessionUser = model.UserSession.getUserId();
            if (sessionUser != null && !sessionUser.isEmpty()) {
                tellerUserId = sessionUser;
            }
        } catch (Exception ex) {}

        // 7. Catat mutasi ke tabel transaksi
        String sqlInsTrx = "INSERT INTO transaksi (transaksi_id, jenis_transaksi, jumlah, saldo_setelah, channel, waktu_transaksi, keterangan, nomor_rekening, pegawai_user_id, pinjaman_id) " +
                           "VALUES (?, 'Pembayaran Angsuran', ?, ?, 'Teller', NOW(), 'Pembayaran angsuran pinjaman', ?, ?, ?)";
        PreparedStatement pstInsTrx = conn.prepareStatement(sqlInsTrx);
        pstInsTrx.setString(1, newTrxId);
        pstInsTrx.setDouble(2, jumlahBayar);
        pstInsTrx.setDouble(3, saldoRekening);
        pstInsTrx.setString(4, nomorRekening);
        pstInsTrx.setString(5, tellerUserId);
        pstInsTrx.setString(6, noPinjaman);
        pstInsTrx.executeUpdate();

        conn.commit();

        // Menggunakan String.format("%.0f", ...) agar nominal tampil sebagai angka normal tanpa format ilmiah (E)
        JOptionPane.showMessageDialog(this, "Pembayaran Angsuran Berhasil!\nJumlah Bayar: Rp " + String.format("%.0f", jumlahBayar) + "\nSisa Pinjaman: Rp " + String.format("%.0f", sisaPinjamanBaru));

        tampilDataPinjaman(); 
        jButton4ActionPerformed(null); // Bersihkan form

    } catch (Exception e) {
        try { if (conn != null) conn.rollback(); } catch (Exception ex) {}
        JOptionPane.showMessageDialog(this, "Gagal memproses angsuran: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton3ActionPerformed

