    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
String noRek = jTextField2.getText().trim();
        
        if (noRek.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih rekening terlebih dahulu dari tabel!");
            return;
        }

        int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Apakah Anda yakin ingin menutup rekening nomor: " + noRek + "?", 
            "Konfirmasi Tutup Rekening", 
            javax.swing.JOptionPane.YES_NO_OPTION);
            
        if (konfirmasi != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        java.sql.Connection conn = null;
        try {
            conn = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/pa_creedy", "root", "");
            conn.setAutoCommit(false);

            String sqlUpdate = "UPDATE rekening SET status_rekening = 'Ditutup', tanggal_tutup = CURDATE() WHERE nomor_rekening = ?";
            java.sql.PreparedStatement pst = conn.prepareStatement(sqlUpdate);
            pst.setString(1, noRek);
            pst.executeUpdate();

            conn.commit();
            javax.swing.JOptionPane.showMessageDialog(this, "Rekening " + noRek + " berhasil ditutup.");

            tampilDataRekening(); 
            jButton4ActionPerformed(null); // Memanggil tombol Bersihkan untuk mereset form

        } catch (Exception e) {
            try { if (conn != null) conn.rollback(); } catch (Exception ex) {}
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal menutup rekening: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton3ActionPerformed

