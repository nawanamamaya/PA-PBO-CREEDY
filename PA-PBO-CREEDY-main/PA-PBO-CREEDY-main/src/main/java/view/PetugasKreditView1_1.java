    private final String userId=UserSession.getUserId();

    private String pencarian="";
    private void siapkan() {
        jTable1.setModel(config.table(new String[]{"Data"},List.of()));
        jLabel8.setText("Pengajuan Menunggu Keputusan");
        jTextArea2.setText("Pilih baris untuk meninjau skor, catatan, dan rekening pencairan. Isi skor 0–100 dan alasan keputusan. Persetujuan mengikuti batas kewenangan akun petugas.");
        jTextField1.setEditable(true);jTextArea1.setEditable(true);jTextArea1.setLineWrap(true);jTextArea1.setWrapStyleWord(true);
        config.combo(jComboBox1,List.of("Disetujui","Ditolak"));
        aktifkanInput(false);
        config.posisiCari(this,jButton1,jButton2);
        jTable1.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        jTable1.getSelectionModel().addListSelectionListener(e -> {
            if(e.getValueIsAdjusting())return;
            int row=jTable1.getSelectedRow();aktifkanInput(row>=0);
            if(row<0){jTextField1.setText("");jTextArea1.setText("");return;}
            int model=jTable1.convertRowIndexToModel(row);
            jTextField1.setText(Objects.toString(jTable1.getModel().getValueAt(model,5),""));
            jTextArea1.setText(Objects.toString(jTable1.getModel().getValueAt(model,7),""));
        });
        muatPengajuan();
    }
    private void muatPengajuan() {
        String cari=pencarian;
        config.run(this, () -> new PegawaiDAO().pengajuan(userId,"Diajukan",cari), rows -> {
            jTable1.setModel(config.table(new String[]{"ID Pinjaman","Nasabah","Tenor (bulan)","Jumlah","Status","Skor","Rekening Pencairan","Catatan"},rows));
            aktifkanInput(false);jTextField1.setText("");jTextArea1.setText("");jTextArea1.setToolTipText(rows.isEmpty()?"Belum ada pengajuan yang sesuai.":"Pilih baris pengajuan, lalu isi alasan keputusan.");
        });
    }
    private void aktifkanInput(boolean aktif) {
        jTextField1.setEnabled(aktif);jTextArea1.setEnabled(aktif);jComboBox1.setEnabled(aktif);jButton3.setEnabled(aktif);jButton4.setEnabled(aktif);
    }
    private int baris() {
        int row=jTable1.getSelectedRow();if(row<0)throw new IllegalArgumentException("Pilih pengajuan yang akan diproses.");
        return jTable1.convertRowIndexToModel(row);
    }
    private void simpanSkor() {
        int row=baris();String id=jTable1.getModel().getValueAt(row,0).toString(),nilai=jTextField1.getText().trim();
        java.math.BigDecimal snapshot=(java.math.BigDecimal)jTable1.getModel().getValueAt(row,5);
        config.run(this, () -> {new com.mycompany.caps_creedy.dao.PinjamanDAO().simpanSkor(userId,id,nilai,snapshot);return true;}, ok -> {config.info(this,"Skor berhasil disimpan.");muatPengajuan();});
    }
    private void putuskan() {
        int row=baris();String id=jTable1.getModel().getValueAt(row,0).toString(),nilai=jTextField1.getText().trim(),keputusan=config.selected(jComboBox1),catatan=jTextArea1.getText().trim();
        java.math.BigDecimal snapshot=(java.math.BigDecimal)jTable1.getModel().getValueAt(row,5);
        com.mycompany.caps_creedy.dao.PinjamanDAO.skor(nilai);
        if(catatan.isBlank() || catatan.length()>200)throw new IllegalArgumentException("Isi alasan keputusan, maksimal 200 karakter.");
        if(javax.swing.JOptionPane.showConfirmDialog(this,"Tetapkan "+id+" sebagai "+keputusan+"?\nSkor: "+nilai+"\nAlasan: "+catatan,"Konfirmasi keputusan",javax.swing.JOptionPane.YES_NO_OPTION)!=javax.swing.JOptionPane.YES_OPTION)return;
        config.run(this, () -> {new com.mycompany.caps_creedy.dao.PinjamanDAO().putuskan(userId,id,keputusan,nilai,catatan,snapshot);return true;}, ok -> {config.info(this,"Keputusan berhasil disimpan.");muatPengajuan();});
    }
    private void cari() {
        String hasil=javax.swing.JOptionPane.showInputDialog(this,"Cari ID pinjaman, NIK, atau nama. Kosongkan untuk menampilkan semua pengajuan.",pencarian);
        if(hasil!=null){pencarian=hasil;muatPengajuan();}
    }

