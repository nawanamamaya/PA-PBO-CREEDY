    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih akun pegawai pada tabel yang ingin dinonaktifkan!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String userId = jTable1.getValueAt(row, 0).toString();
        int confirm = JOptionPane.showConfirmDialog(this, "Apakah Anda yakin ingin menonaktifkan akun ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection conn = config.configDB();
                String sql = "UPDATE users SET status='Tidak Aktif' WHERE user_id=?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, userId);
                pst.executeUpdate();

                JOptionPane.showMessageDialog(this, "Status akun berhasil diubah menjadi Tidak Aktif!");
                tampilDataPegawai();
                bersihkanForm();

            } catch (HeadlessException | SQLException e) {
                JOptionPane.showMessageDialog(this, "Gagal mengubah status: " + e.getMessage(), "Error Database", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String nip = jTextField2.getText().trim();
        String password = jTextField3.getText().trim();
        String nama = jTextField4.getText().trim();
        String role = jComboBox1.getSelectedItem().toString();

    if (nip.isEmpty() || password.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua field input (NIP, Password, Nama) harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
    }
    
    Connection conn = null;
    try {
            conn = config.configDB();
            conn.setAutoCommit(false);
        
            String userId = generateNextUserId(conn);
            String email = role.toLowerCase().replace(" ", "") + "." + userId.toLowerCase() + "@creedy.co.id";
            String batasPersetujuan = role.equals("Petugas Kredit") ? "500 Juta" : (role.equals("Teller") ? "100 Juta" : "Rp0");
        
            String sqlUser = "INSERT INTO users (user_id, email, password, nama_lengkap, status, user_type) VALUES (?, ?, ?, ?, 'Aktif', 'Pegawai')";
            PreparedStatement pstUser = conn.prepareStatement(sqlUser);
            pstUser.setString(1, userId);
            pstUser.setString(2, email);
            pstUser.setString(3, password);
            pstUser.setString(4, nama);
            pstUser.executeUpdate();
            
            String sqlPegawai = "INSERT INTO pegawai (nip, user_id, jabatan, cabang_id, batas_persetujuan) VALUES (?, ?, ?, 'CBG001', ?)";
            PreparedStatement pstPegawai = conn.prepareStatement(sqlPegawai);
            pstPegawai.setString(1, nip);
            pstPegawai.setString(2, userId);
            pstPegawai.setString(3, role);
            pstPegawai.setString(4, batasPersetujuan);
            pstPegawai.executeUpdate();

        conn.commit();
        JOptionPane.showMessageDialog(this, "Akun pegawai berhasil ditambahkan dengan User ID: " + userId);
        
        tampilDataPegawai();
        bersihkanForm();


    } catch (HeadlessException | SQLException e) {
        if (conn != null) {
            try { conn.rollback(); } catch (SQLException ex) { logger.log(java.util.logging.Level.SEVERE, null, ex); }
        }
        JOptionPane.showMessageDialog(this, "Gagal menambah akun: " + e.getMessage(), "Error Database", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton2ActionPerformed

