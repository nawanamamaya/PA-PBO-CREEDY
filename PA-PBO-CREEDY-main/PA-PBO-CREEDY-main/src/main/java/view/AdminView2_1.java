    private void tampilDataPegawai() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("User ID");
        model.addColumn("NIP");
        model.addColumn("Nama");
        model.addColumn("Role");
        model.addColumn("Status");
    
        

        try {
            Connection conn = config.configDB(); 
            Statement stmt = conn.createStatement();
            
            String sql = "SELECT u.user_id, p.nip, u.nama_lengkap, p.jabatan, u.status " +
                         "FROM users u " +
                         "INNER JOIN pegawai p ON u.user_id = p.user_id " +
                         "WHERE u.user_type = 'Pegawai'"; 
                         
            ResultSet res = stmt.executeQuery(sql);

        while (res.next()) {
                model.addRow(new Object[]{
                    res.getString("user_id"),
                    res.getString("nip"),
                    res.getString("nama_lengkap"),
                    res.getString("jabatan"),
                    res.getString("status")
                });
            }
            jTable1.setModel(model);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, 
                "Gagal mengambil data pegawai: " + e.getMessage(),
                "Error Database", 
                JOptionPane.ERROR_MESSAGE);
        }
    }

