private String generateNextUserId(java.sql.Connection conn) {
    String nextId = "USR101"; // Default jika database kosong di atas USR100
    try {
        // Mengambil nomor angka terbesar dari user_id yang berawalan 'USR'
        String sql = "SELECT MAX(CAST(SUBSTRING(user_id, 4) AS UNSIGNED)) AS max_id FROM users WHERE user_id LIKE 'USR%'";
        java.sql.PreparedStatement pst = conn.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            int maxId = rs.getInt("max_id");
            if (maxId > 0) {
                // Tambahkan 1 dari ID tertinggi saat ini
                nextId = String.format("USR%03d", maxId + 1);
            }
        }
    } catch (java.sql.SQLException e) {
        System.out.println("Error Auto ID: " + e.getMessage());
    }
    return nextId;
}

