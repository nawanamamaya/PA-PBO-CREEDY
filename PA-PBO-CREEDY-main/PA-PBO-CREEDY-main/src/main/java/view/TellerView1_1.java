    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
String nik = jTextField2.getText().trim();
        String setoranAwalStr = jTextField3.getText().trim();
        String nomorRekening = jTextField7.getText().trim();
        String jenisRekening = jComboBox1.getSelectedItem().toString();

        if (nik.isEmpty() || setoranAwalStr.isEmpty() || nomorRekening.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih nasabah dari tabel dan isi setoran awal!");
            return;
        }

        double setoranAwal = 0;
        try {
            setoranAwal = Double.parseDouble(setoranAwalStr);
            if (setoranAwal < 50000) {
                javax.swing.JOptionPane.showMessageDialog(this, "Setoran awal minimal Rp 50.000!");
                return;
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Setoran awal harus berupa angka!");
            return;
        }

        java.sql.Connection conn = null;
        try {
            conn = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/pa_creedy", "root", "");
            conn.setAutoCommit(false);

            String sqlUser = "SELECT user_id FROM nasabah WHERE nik = ?";
            java.sql.PreparedStatement pstUser = conn.prepareStatement(sqlUser);
            pstUser.setString(1, nik);
            java.sql.ResultSet rsUser = pstUser.executeQuery();
            
            if (!rsUser.next()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Data Nasabah tidak ditemukan!");
                return;
            }
            String nasabahUserId = rsUser.getString("user_id");

            String tellerUserId = "USR002";
            try {
            String sessionUser = model.UserSession.getUserId();
                if (sessionUser != null && !sessionUser.isEmpty()) {
                    tellerUserId = sessionUser;
                }
            } catch (Exception ex) {}

            String cabangId = "CBG001";
            String sqlCabang = "SELECT cabang_id FROM pegawai WHERE user_id = ?";
            java.sql.PreparedStatement pstCabang = conn.prepareStatement(sqlCabang);
            pstCabang.setString(1, tellerUserId);
            java.sql.ResultSet rsCabang = pstCabang.executeQuery();
            if (rsCabang.next()) {
                cabangId = rsCabang.getString("cabang_id");
            }

            String sqlRek = "INSERT INTO rekening (nomor_rekening, jenis_rekening, saldo, status_rekening, tanggal_buka, cabang_id, nasabah_user_id) " +
                            "VALUES (?, ?, ?, 'Aktif', CURDATE(), ?, ?)";
            java.sql.PreparedStatement pstRek = conn.prepareStatement(sqlRek);
            pstRek.setString(1, nomorRekening);
            pstRek.setString(2, jenisRekening);
            pstRek.setDouble(3, setoranAwal);
            pstRek.setString(4, cabangId);
            pstRek.setString(5, nasabahUserId);
            pstRek.executeUpdate();

            java.sql.Statement stmtTrx = conn.createStatement();
            java.sql.ResultSet rsTrx = stmtTrx.executeQuery("SELECT MAX(CAST(SUBSTRING(transaksi_id, 4) AS UNSIGNED)) AS max_trx FROM transaksi");
            int nextTrxId = 1;
            if (rsTrx.next()) {
                nextTrxId = rsTrx.getInt("max_trx") + 1;
            }
            String newTrxId = String.format("TRX%04d", nextTrxId);

            String sqlTrx = "INSERT INTO transaksi (transaksi_id, jenis_transaksi, jumlah, saldo_setelah, channel, waktu_transaksi, keterangan, nomor_rekening, pegawai_user_id) " +
                            "VALUES (?, 'Setoran Tunai', ?, ?, 'Teller', NOW(), 'Setoran awal pembukaan rekening', ?, ?)";
            java.sql.PreparedStatement pstTrx = conn.prepareStatement(sqlTrx);
            pstTrx.setString(1, newTrxId);
            pstTrx.setDouble(2, setoranAwal);
            pstTrx.setDouble(3, setoranAwal);
            pstTrx.setString(4, nomorRekening);
            pstTrx.setString(5, tellerUserId);
            pstTrx.executeUpdate();

            conn.commit();
            javax.swing.JOptionPane.showMessageDialog(this, "Rekening Berhasil Dibuka!\nNo. Rekening: " + nomorRekening + "\nSaldo: Rp " + setoranAwal);

            jButton4ActionPerformed(null);

        } catch (Exception e) {
            try { if (conn != null) conn.rollback(); } catch (Exception ex) {}
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Buka Rekening: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton3ActionPerformed

